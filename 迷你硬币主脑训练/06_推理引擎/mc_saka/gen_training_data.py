#!/usr/bin/env python3
"""
Timing Gate 训练数据生成器
输出格式：每行一个 JSON，可直接用于 SFT/GRPO 训练
"""
import json, random

random.seed(42)

# ============================================================
# 数据源
# ============================================================

YES_CASES = [
    # 招呼
    "你好呀", "早上好", "下午好", "晚上好", "hi", "hello", "Hey",
    "你好", "您好", "好久不见", "你还在吗", "在吗",
    # 提问
    "你在干嘛", "你吃饭了吗", "你叫什么名字", "你是谁",
    "你今天心情怎么样", "你喜欢什么", "你会做什么",
    # 调戏/骚扰
    "你的腿好长啊", "你好可爱", "你好漂亮", "你好骚啊",
    "你做我女朋友吧", "亲一个", "你身材真好",
    # 抱怨/情绪
    "我好难过", "今天真烦", "我好累", "我心情不好",
    "我好孤独啊", "没人陪我说话", "我失恋了",
    # 挑衅
    "你不行啊", "就这", "你居然敢这样对我",
    "你也就这样了", "你有什么了不起的",
    # 命令
    "帮我查天气", "讲个笑话", "唱首歌",
    "推荐一部电影", "帮我分析一下", "查一下这个",
    # 评价模型
    "你真聪明", "你真笨", "你今天真好看",
    "你比Siri好用", "你反应好快",
    # 搭话
    "今天天气不错", "刚才那把打得不错", "这个游戏好玩吗",
    "你玩过这个吗", "你觉得呢",
    # 对方话题涉及模型
    "我对你有点心动了", "在干嘛呢小可爱",
    "来陪我聊聊天", "今天有空吗",
    "我心情不好能陪我说说话吗", "你是不是不喜欢我了",
]

NO_CASES = [
    # 弹幕路过
    "（弹幕路过）", "（刷屏）", "（测试）", "（打卡）",
    # 自言自语（不是在问模型）
    "有人知道吗", "这个怎么弄", "有没有人教教我",
    "我搞不懂", "好复杂啊", "算了不弄了",
    # 单纯笑声
    "哈哈", "哈哈哈", "hhhh", "xswl", "笑死",
    "2333", "23333", "wwwwww",
    # 无意义
    "111", "1111", "666", "6666", "222",
    "。。。。。。", "。。", "....",
    "吐了", "绝了", "好家伙",
    # 对别人说话
    "Vedal你看看这个", "Vedal来一下", "大家觉得呢",
    "你们有没有遇到过", "这个作者是谁",
    # 背景聊天
    "我昨天去了一家店", "我跟你说个事",
    "这个游戏我玩过", "我推荐你去看看",
    # 语气词/低信息量
    "啊", "哦", "嗯", "行", "好", "OK",
    "好吧", "知道了", "了解了",
    # 刷屏/重复
    "冲冲冲", "好耶", "加油加油",
]

WAIT_CASES = [
    # 对方思考
    "等等让我想想", "嗯…", "让我想一下",
    "那个…", "就是…", "怎么说呢",
    # 不完整
    "我想说", "其实", "不过",
    # 模糊输入
    "？", "？？", "。。", "…",
    # 刚回完不久的标志
    "（系统消息：模型就绪）",
    # 模棱两可
    "你猜", "你说呢",
    "这可不一定", "也许吧",
]

# ============================================================
# 生成完整数据集
# ============================================================

dataset = []

for msg in YES_CASES:
    dataset.append({"input": msg, "output": "yes"})

for msg in NO_CASES:
    dataset.append({"input": msg, "output": "no"})

for msg in WAIT_CASES:
    dataset.append({"input": msg, "output": "wait"})

random.shuffle(dataset)

# ============================================================
# 输出
# ============================================================

print(f"总共 {len(dataset)} 条")
print(f"  yes: {len(YES_CASES)} 条")
print(f"  no:  {len(NO_CASES)} 条")
print(f"  wait: {len(WAIT_CASES)} 条")
print()

# 输出 JSONL
for item in dataset:
    print(json.dumps(item, ensure_ascii=False))

print("---DONE---")
